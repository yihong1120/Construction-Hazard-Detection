from __future__ import annotations

import argparse
import json
import re
import shlex
from pathlib import Path

from src.settings.sessions import SESSION_POLICY
from src.settings.sessions import SessionPolicy

ROOT = Path(__file__).resolve().parent


def generated_files(policy: SessionPolicy) -> dict[Path, str]:
    template = ROOT / 'visionnaire-realm.template.json'
    realm = json.loads(template.read_text())
    realm.update(policy.realm_settings())
    for client in realm['clients']:
        if client['clientId'] in policy.clients:
            client.setdefault('attributes', {}).update(
                policy.client_attributes(),
            )
    variables = {
        'SSO_SESSION_IDLE_SECONDS': policy.idle_seconds,
        'SSO_SESSION_MAX_SECONDS': policy.maximum_seconds,
        'ACCESS_TOKEN_SECONDS': policy.access_token_seconds,
        'DEFAULT_CLIENT_IDLE_SECONDS': policy.other_client_idle_seconds,
        'DEFAULT_CLIENT_MAX_SECONDS': policy.other_client_maximum_seconds,
    }
    shell = (
        '# Generated by python -m '
        'deploy.keycloak.session_policy; edit '
        'src/settings/session_policy.json.\n'
    )
    shell += ''.join(f'{name}={value}\n' for name, value in variables.items())
    shell += 'SESSION_POLICY_CLIENTS=(' + shlex.join(policy.clients) + ')\n'
    shell += (
        'SESSION_POLICY_OPTIONAL_CLIENTS=('
        + shlex.join(policy.optional_clients)
        + ')\n'
    )
    for name, mapping in (
        ('SESSION_POLICY_REALM', policy.realm_settings()),
        ('SESSION_POLICY_ATTRIBUTES', policy.client_attributes()),
    ):
        shell += f'declare -A {name}=(\n'
        shell += ''.join(
            f'    [{shlex.quote(key)}]={shlex.quote(str(value))}\n'
            for key, value in mapping.items()
        )
        shell += ')\n'
    example = ROOT.parents[1] / '.env.example'
    env = re.sub(
        r'(?m)^BFF_SESSION_TTL_SECONDS=.*$',
        f'BFF_SESSION_TTL_SECONDS={policy.idle_seconds}',
        example.read_text(),
    )
    return {
        template: json.dumps(realm, indent=2, ensure_ascii=False) + '\n',
        ROOT / 'session-policy.env': shell,
        example: env,
    }


def main() -> None:
    parser = argparse.ArgumentParser(
        description=(
            'Generate Keycloak session settings from the ' 'canonical policy'
        ),
    )
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    drift = []
    for path, expected in generated_files(SESSION_POLICY).items():
        if not path.exists() or path.read_text() != expected:
            drift.append(path.name)
            if not args.check:
                path.write_text(expected)
    if args.check and drift:
        parser.exit(
            1,
            'Session policy output is stale: ' + ', '.join(drift) + '\n',
        )


if __name__ == '__main__':
    main()
