ALGORITHM_EXPLANATION = (
    'Cone clustering and restricted-zone decisions: implementation '
    'reference\n\n1. Input and centre points\nEach detection row is '
    '[x1,y1,x2,y2,confidence,class_id,...], in original-image pixels. The x '
    'axis points right and the y axis points '
    'down.\nDangerDetector.detect_danger first normalises box corner order '
    'with normalise_bbox and filters machinery using optional '
    'tracking/movement fields.\nClass IDs are 6=cone, 5=person, 8=machinery '
    'and 10=vehicle. The geometry helpers themselves assume valid input box '
    'coordinates.\nBoth cone and person centres are cx=(x1+x2)/2 and '
    'cy=(y1+y2)/2.\nThe decision point is the box centre, rather than the '
    'feet, bottom-centre or a segmentation centroid. Box/zone overlap alone '
    'is insufficient.\n\n2. Clustering\nThe implementation uses '
    'sklearn.cluster.HDBSCAN(min_samples=3,min_cluster_size=2,copy=True).\nIts'
    ' input is the two-dimensional pixel coordinates of all detected cone '
    'centres in the current image, using the default Euclidean metric.\nFewer '
    'than three cones return an empty region list. Label -1 denotes noise and '
    'is skipped.\nAlthough min_cluster_size is 2, a retained group still '
    'needs at least three points before a hull is appended.\nCluster labels '
    'identify this particular fit; they are not persistent cross-frame zone '
    'identities.\nThe complete observed parameters are recorded in '
    'environment.json, including allow_single_cluster=False.\n\n3. '
    'Boundaries\nEach non-noise group with at least three centres is '
    'processed separately with MultiPoint(cluster_points).convex_hull.\nSepara'
    'te hulls preserve gaps between different groups. Within a group, a '
    'convex hull fills concavities.\nThe implementation does not '
    'automatically merge every group into one hull, use manually specified '
    'site boundaries or convert coordinates into ground-plane '
    'metres.\npolygons_to_coords exports Polygon/MultiPolygon boundaries as '
    'vertex lists for display.\n\n4. Person-in-zone decision\nFor each '
    'class-5 detection, the box centre is tested with '
    'region.contains(Point(cx,cy)) against the individual hulls.\nA True '
    "result for any region triggers that person's cone-zone decision. Points "
    'exactly on a polygon boundary are excluded.\nThe counting helper uses a '
    'set of centre-coordinate tuples. Multiple boxes sharing exactly the same '
    'centre count once; tracking IDs are not used for this deduplication.\nA '
    'positive count produces warning_people_in_controlled_area.count.\nThis '
    'is a per-image geometric decision, not evidence of a continuous '
    'entry/exit event or a tracked individual.\n\n5. Observed edge '
    'behaviour\nHaving at least three points is necessary but does not '
    'guarantee a usable HDBSCAN group. In the recorded four-corner '
    'single-group probe, all points are noise under the current '
    'defaults.\nThe production code does not check hull geometry type or area '
    'before appending it. Collinear points can yield LineStrings. Their '
    'contains test can count a person while coordinate export omits the line '
    'geometry.\nedge_case_observations.csv/JSON reproduce both limitations. '
    'Production algorithms were not modified to prepare this evidence.\nThe '
    'geometries used for the formal figures were previously verified as valid '
    'Polygons.\n\n6. Occupant exclusion and proximity\nSpatial-index '
    'candidates are processed one at a time. Six bounding-box conditions are '
    'checked first.\nIf any candidate satisfies the occupant rule, that '
    "person's machinery/vehicle proximity flags are excluded, including flags "
    'previously set by another candidate.\nOtherwise the person/object '
    'box-area ratio must be <=0.10 for a vehicle or <=0.05 for '
    'machinery.\nThe remaining checks are dx<=5*person_width and '
    'dy<=1.5*person_height.\ndx=min(|p_right-v_left|,|p_left-v_right|); '
    'dy=min(|p_bottom-v_top|,|p_top-v_bottom|).\nThese are pixel box-edge '
    'indicators, not calibrated nearest ground distances. The occupant '
    'heuristic is not an independently trained driver-identity '
    'classifier.\nOccupant exclusion applies only to proximity rules, not to '
    'cone-zone warnings.\n'
)

